package api

import (
	"context"
	"sync"

	"preactvillacarmen/internal/sqldb"
)

var (
	ensureModificationHistoryOnce sync.Once
	ensureModificationHistoryErr  error
)

func (s *Server) ensureModificationHistoryTable(ctx context.Context) error {
	ensureModificationHistoryOnce.Do(func() {
		_, ensureModificationHistoryErr = s.db.ExecContext(ctx, nativeSQL(`
			CREATE TABLE IF NOT EXISTS modification_history (
				id INT AUTO_INCREMENT PRIMARY KEY,
				restaurant_id INT NOT NULL DEFAULT 1,
				booking_id INT NOT NULL,
				customer_phone VARCHAR(20),
				field_modified VARCHAR(50) NOT NULL,
				old_value TEXT,
				new_value TEXT,
				modification_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

				INDEX idx_booking (booking_id),
				INDEX idx_restaurant_booking (restaurant_id, booking_id),
				INDEX idx_date (modification_date),
				INDEX idx_phone (customer_phone),

				FOREIGN KEY (booking_id) REFERENCES bookings(id) ON DELETE CASCADE
			) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci
		`, modificationHistoryPGCreate))
		if ensureModificationHistoryErr != nil {
			return
		}
		if sqlDialect == sqldb.Postgres {
			// Same names/types as the migration plan (plan.sql) so this is a
			// no-op on the imported baseline and creates it on an empty DB.
			for _, q := range modificationHistoryPGIndexes {
				if _, ensureModificationHistoryErr = s.db.ExecContext(ctx, pgOnlySQL(q)); ensureModificationHistoryErr != nil {
					return
				}
			}
		}

		// Backward compatibility: if the table existed without multitenant columns, add them best-effort.
		_, _ = s.db.ExecContext(ctx, nativeSQL("ALTER TABLE modification_history ADD COLUMN restaurant_id INT NOT NULL DEFAULT 1",
			`ALTER TABLE "modification_history" ADD COLUMN IF NOT EXISTS "restaurant_id" integer NOT NULL DEFAULT 1`))
		_, _ = s.db.ExecContext(ctx, nativeSQL("ALTER TABLE modification_history ADD INDEX idx_restaurant_booking (restaurant_id, booking_id)",
			`CREATE INDEX IF NOT EXISTS "ix__modification_history__idx_restaurant_booking" ON "modification_history" ("restaurant_id", "booking_id")`))

		// Best-effort: table comment (non-critical).
		_, _ = s.db.ExecContext(ctx, nativeSQL("ALTER TABLE modification_history COMMENT = 'Historial de todas las modificaciones de reservas realizadas por clientes'",
			`COMMENT ON TABLE "modification_history" IS 'Historial de todas las modificaciones de reservas realizadas por clientes'`))
	})

	return ensureModificationHistoryErr
}

// PG twin of the runtime MySQL DDL, mirroring full-pg-plan/plan.sql names.
// Collation of the varchar/text columns follows plan.sql (CI collation
// decision still pending in the collation ledger).
const modificationHistoryPGCreate = `
	CREATE TABLE IF NOT EXISTS "modification_history" (
		"id" integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
		"booking_id" integer NOT NULL,
		"customer_phone" varchar(20),
		"field_modified" varchar(50) NOT NULL,
		"old_value" text,
		"new_value" text,
		"modification_date" timestamptz(0) DEFAULT CURRENT_TIMESTAMP,
		CONSTRAINT "rng__modification_history__old_value__0" CHECK (octet_length("old_value") <= 65535),
		CONSTRAINT "rng__modification_history__new_value__0" CHECK (octet_length("new_value") <= 65535),
		CONSTRAINT "pk__modification_history" PRIMARY KEY ("id"),
		CONSTRAINT "fk__modification_history__modification_history_ibfk_1" FOREIGN KEY ("booking_id") REFERENCES "bookings" ("id") ON UPDATE RESTRICT ON DELETE CASCADE
	)
`

var modificationHistoryPGIndexes = []string{
	`CREATE INDEX IF NOT EXISTS "ix__modification_history__idx_booking" ON "modification_history" ("booking_id")`,
	`CREATE INDEX IF NOT EXISTS "ix__modification_history__idx_date" ON "modification_history" ("modification_date")`,
	`CREATE INDEX IF NOT EXISTS "ix__modification_history__idx_phone" ON "modification_history" ("customer_phone")`,
}
