CREATE TABLE IF NOT EXISTS pos_cover_adjustments (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    restaurant_id INT NOT NULL,
    visit_id BIGINT UNSIGNED NULL,
    service_date DATE NOT NULL,
    service_type ENUM('LUNCH','DINNER','OTHER') NOT NULL DEFAULT 'OTHER',
    delta_covers INT NOT NULL,
    reason VARCHAR(500) NOT NULL,
    idempotency_key VARCHAR(120) NOT NULL,
    actor_user_id INT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uq_pos_cover_adjustment_idempotency (restaurant_id, idempotency_key),
    KEY idx_pos_cover_adjustments_key (restaurant_id, service_date, service_type, created_at),
    CONSTRAINT fk_pos_cover_adjustments_restaurant FOREIGN KEY (restaurant_id) REFERENCES restaurants(id) ON DELETE CASCADE,
    CONSTRAINT fk_pos_cover_adjustments_visit FOREIGN KEY (restaurant_id, visit_id) REFERENCES pos_visits(restaurant_id, id),
    CONSTRAINT chk_pos_cover_adjustment CHECK (delta_covers <> 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
