CREATE TABLE IF NOT EXISTS restaurant_google_business (
  restaurant_id integer NOT NULL,
  google_email varchar(255) NOT NULL DEFAULT '',
  refresh_token_encrypted text NULL,
  account_name varchar(255) NOT NULL DEFAULT '',
  location_name varchar(255) NOT NULL DEFAULT '',
  location_title varchar(255) NOT NULL DEFAULT '',
  auto_publish_min_stars smallint NOT NULL DEFAULT 0,
  formality varchar(8) NOT NULL DEFAULT 'tu',
  signature varchar(160) NOT NULL DEFAULT '',
  complaint_contact varchar(255) NOT NULL DEFAULT '',
  sync_enabled smallint NOT NULL DEFAULT 1,
  last_sync_at timestamp NULL,
  last_sync_error varchar(500) NOT NULL DEFAULT '',
  connected_at timestamp NULL,
  updated_at timestamp NOT NULL DEFAULT (date_trunc('second', statement_timestamp()) AT TIME ZONE 'UTC'),
  PRIMARY KEY (restaurant_id)
);

CREATE TABLE IF NOT EXISTS google_reviews (
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  restaurant_id integer NOT NULL,
  review_name varchar(255) NOT NULL,
  reviewer_name varchar(255) NOT NULL DEFAULT '',
  star_rating smallint NOT NULL DEFAULT 0,
  comment text NULL,
  review_created_at timestamp NULL,
  review_updated_at timestamp NULL,
  reply text NULL,
  status varchar(16) NOT NULL DEFAULT 'pending',
  error varchar(500) NOT NULL DEFAULT '',
  published_at timestamp NULL,
  created_at timestamp NOT NULL DEFAULT (date_trunc('second', statement_timestamp()) AT TIME ZONE 'UTC'),
  updated_at timestamp NOT NULL DEFAULT (date_trunc('second', statement_timestamp()) AT TIME ZONE 'UTC'),
  PRIMARY KEY (id),
  CONSTRAINT uq_google_reviews_name UNIQUE (review_name)
);
CREATE INDEX IF NOT EXISTS idx_google_reviews_status ON google_reviews (restaurant_id, status);
CREATE INDEX IF NOT EXISTS idx_google_reviews_created ON google_reviews (restaurant_id, review_created_at);

